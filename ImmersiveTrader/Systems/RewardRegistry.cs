    public static void Validate()
    {
        int missingRoutes = 0;
        var seen = new HashSet<string>();
        var missingPrefabs = new HashSet<string>();
        foreach (var reward in Rewards)
        {
            string key = reward.TraderId + "|" + reward.TreasureId;
            if (!seen.Add(key))
                Plugin.Log.LogWarning($"Duplicate cargo route: {key}");

            if (ObjectDB.instance?.GetItemPrefab(reward.ItemPrefab) != null)
                continue;

            missingRoutes++;
            missingPrefabs.Add(reward.ItemPrefab);
        }

        foreach (string prefab in missingPrefabs)
            Plugin.Log.LogWarning($"Cargo reward prefab genuinely missing after ObjectDB ready: {prefab}");

        Plugin.Log.LogInfo(
            $"Cargo routes ready: {Rewards.Count}; unique: {seen.Count}; missing reward routes: {missingRoutes}; missing prefab names: {missingPrefabs.Count}");
    }
